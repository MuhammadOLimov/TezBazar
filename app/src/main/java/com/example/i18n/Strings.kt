object StringsRepository {
    fun get(language: AppLanguage): LocalizedStrings = when (language) {
        AppLanguage.UZ -> uzbekStrings
        AppLanguage.RU -> russianStrings
        AppLanguage.EN -> englishStrings
    }

    fun formatUzs(amount: Long, language: AppLanguage): String {
        val symbols = DecimalFormatSymbols().apply {
            groupingSeparator = if (language == AppLanguage.EN) ',' else ' '
        }
        val formatted = DecimalFormat("#,###", symbols).format(amount)
        return when (language) {
            AppLanguage.UZ -> "$formatted so'm"
            AppLanguage.RU -> "$formatted сум"
            AppLanguage.EN -> "$formatted UZS"
        }
    }

