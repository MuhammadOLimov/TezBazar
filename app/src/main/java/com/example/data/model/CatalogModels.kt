package com.example.data.model

import com.example.i18n.AppLanguage

data class Category(
    val id: String,
    val nameUz: String,
    val nameRu: String,
    val nameEn: String,
    val iconKey: String,
    val accentColorHex: Long
) {
    fun localizedName(language: AppLanguage): String = when (language) {
        AppLanguage.UZ -> nameUz
        AppLanguage.RU -> nameRu
        AppLanguage.EN -> nameEn
    }
}

data class Product(
    val id: String,
    val titleUz: String,
    val titleRu: String,
    val titleEn: String,
    val descUz: String,
    val descRu: String,
    val descEn: String,
    val categoryId: String,
    val priceUzs: Long,
    val oldPriceUzs: Long? = null,
    val unitUz: String,
    val unitRu: String,
    val unitEn: String,
    val rating: Double,
    val reviewCount: Int,
    val deliveryMinutes: Int,
    val popularityScore: Int,
    val badgeUz: String? = null,
    val badgeRu: String? = null,
    val badgeEn: String? = null,
    val imageKey: String,
    val tags: List<String> = emptyList()
) {
    fun localizedTitle(language: AppLanguage): String = when (language) {
        AppLanguage.UZ -> titleUz
        AppLanguage.RU -> titleRu
        AppLanguage.EN -> titleEn
    }

    fun localizedDesc(language: AppLanguage): String = when (language) {
        AppLanguage.UZ -> descUz
        AppLanguage.RU -> descRu
        AppLanguage.EN -> descEn
    }

    fun localizedUnit(language: AppLanguage): String = when (language) {
        AppLanguage.UZ -> unitUz
        AppLanguage.RU -> unitRu
        AppLanguage.EN -> unitEn
    }

    fun localizedBadge(language: AppLanguage): String? = when (language) {
        AppLanguage.UZ -> badgeUz
        AppLanguage.RU -> badgeRu
        AppLanguage.EN -> badgeEn
    }

    val discountPercent: Int
        get() {
            val old = oldPriceUzs ?: return 0
            if (old <= priceUzs || old <= 0L) return 0
            return (((old - priceUzs) * 100) / old).toInt()
        }

    // Uzum Nasiya style 12-month installment calculation
    val monthlyInstallmentUzs: Long
        get() = ((priceUzs * 1.18) / 12.0).toLong().coerceAtLeast(1000L)
}

